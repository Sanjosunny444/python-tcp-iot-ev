"""
AES-128-ECB encryption/decryption for DiLu CCU protocol.

Per spec section 4.3:
  - Only data content + check code (CRC) are encrypted
  - Start code (5155) and length field are NOT encrypted
  - Length field = content size BEFORE encryption
  - Encrypted block = content + CRC + random padding to multiple of 16
  - AES key: session_key (16 bytes), derived from auth

Key hierarchy:
  - Root key (16 bytes): pre-configured, used to decrypt session key
  - Session key (16 bytes): generated by device, encrypted with root key,
    sent in auth (CMD 0x04). Used for all subsequent communication.
"""

import os
from Crypto.Cipher import AES

BLOCK_SIZE = 16  # AES-128 block size


def decrypt_session_key(encrypted_session_key: bytes, root_key: bytes) -> bytes:
    """Decrypt the session key from the auth packet using the root key."""
    cipher = AES.new(root_key, AES.MODE_ECB)
    return cipher.decrypt(encrypted_session_key)


def decrypt_packet_payload(encrypted_data: bytes, content_len: int, session_key: bytes):
    """
    Decrypt an incoming encrypted payload from the device.

    Args:
        encrypted_data: the encrypted bytes read after the length field
        content_len: original content length from the length field (plaintext)
        session_key: 16-byte AES key

    Returns:
        (content, crc) tuple
        content: decrypted content bytes (content_len bytes)
        crc: decrypted CRC bytes (2 bytes)
    """
    cipher = AES.new(session_key, AES.MODE_ECB)
    decrypted = cipher.decrypt(encrypted_data)

    # First content_len bytes = content
    content = decrypted[:content_len]
    # Next 2 bytes = CRC
    crc = decrypted[content_len:content_len + 2]
    # Remaining bytes = random padding (discarded)

    return content, crc


def encrypt_packet_payload(content: bytes, crc: bytes, session_key: bytes) -> bytes:
    """
    Encrypt content + CRC for sending to the device.

    Args:
        content: the data content bytes
        crc: 2-byte CRC16 of content
        session_key: 16-byte AES key

    Returns:
        Encrypted bytes (length is a multiple of 16)

    Per spec: if content + CRC is not a multiple of 16, random bytes
    are appended after the CRC before encryption.
    """
    plaintext = content + crc

    # Pad to next multiple of 16 with random bytes
    remainder = len(plaintext) % BLOCK_SIZE
    if remainder != 0:
        pad_len = BLOCK_SIZE - remainder
        plaintext = plaintext + os.urandom(pad_len)

    cipher = AES.new(session_key, AES.MODE_ECB)
    return cipher.encrypt(plaintext)


def calc_encrypted_size(content_len: int) -> int:
    """
    Calculate how many bytes to read for the encrypted block,
    given the original content length.

    Encrypted block = ceil((content_len + 2) / 16) * 16
    The +2 is for the CRC bytes.
    """
    total = content_len + 2  # content + CRC
    remainder = total % BLOCK_SIZE
    if remainder == 0:
        return total
    return total + (BLOCK_SIZE - remainder)


def build_encrypted_packet(content: bytes, session_key: bytes) -> bytes:
    """
    Build a complete DiLu packet with encrypted payload.

    Returns: 0x5155 + length(2 LE) + encrypted(content + CRC + padding)

    Length field = content size before encryption (per spec).
    """
    from shared import calculate_crc16

    crc = calculate_crc16(content)
    encrypted = encrypt_packet_payload(content, crc, session_key)
    length = len(content).to_bytes(2, "little")

    return b"\x51\x55" + length + encrypted
